// Generates the DESKTOP copy of the CRM import wizard from the web app's TypeScript, so the two can never drift apart (the same idea as the
// connections hub generator): the logic in src/lib/import/*.ts and the screens ImportWizardModal / ImportUndoPanel / ImportHistoryModal / Modal.
//
//   node scripts/port_import_desktop.mjs                 (from raptor-app/)  -> writes <Raptor B2B>/raptor-ui/src/pages/crm/import/
//   node scripts/port_import_desktop.mjs <output dir>    to write somewhere else
//
// It only strips the types (TypeScript's own transpiler, JSX kept) and rewrites the few import paths and two theme colours that differ. Never edit
// the generated files by hand: change the web source and run this again.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const ts = require('typescript');
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const OUT = path.resolve(process.argv[2] || 'C:/Users/Asus/Desktop/shoonya origins tech/Raptor B2B/raptor-ui/src/pages/crm/import');

const HEADER = '// GENERATED by raptor-app/scripts/port_import_desktop.mjs from the web app\'s TypeScript. Do not edit here: change the web source and run the script again.\n';

function strip(source, fileName, jsx) {
  return ts.transpileModule(source, {
    fileName,
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2020, jsx: jsx ? ts.JsxEmit.Preserve : undefined, verbatimModuleSyntax: false, removeComments: false },
  }).outputText;
}

function write(rel, text) {
  const file = path.join(OUT, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, HEADER + text.replace(/\r\n/g, '\n'));
  return file;
}

const written = [];

// ---- the logic: src/lib/import/*.ts -> import/lib/*.js
const libDir = path.join(ROOT, 'src/lib/import');
for (const name of fs.readdirSync(libDir).filter((f) => f.endsWith('.ts'))) {
  let js = strip(fs.readFileSync(path.join(libDir, name), 'utf8'), name, false);
  js = js.replace(/(from\s+['"]\.\/[\w-]+)\.ts(['"])/g, '$1.js$2');                                   // './values.ts' -> './values.js'
  js = js.replace(/import\(\s*['"]\.\.\/supabaseClient\.ts['"]\s*\)/g, "import('../../../../supabaseClient')");   // the desktop's own database client
  written.push(write(`lib/${name.replace(/\.ts$/, '.js')}`, js));
}

// ---- the screens: src/components/crm/{Modal,ImportUndoPanel,ImportHistoryModal,ImportWizardModal}.tsx -> import/*.js
for (const name of ['Modal', 'ImportUndoPanel', 'ImportHistoryModal', 'ImportWizardModal']) {
  let js = strip(fs.readFileSync(path.join(ROOT, 'src/components/crm', `${name}.tsx`), 'utf8'), `${name}.tsx`, true);
  js = js.replace(/(['"])\.\.\/\.\.\/lib\/import\/([\w-]+)\1/g, "'./lib/$2'");                          // the shared logic
  js = js.replace(/(['"])\.\.\/\.\.\/lib\/pipelineStages\1/g, "'../pipelineStages'");                  // the desktop has its own copy of the pipeline helpers
  js = js.replace(/ *\/\/ eslint-disable-line react-hooks\/exhaustive-deps/g, '');                          // the desktop's lint setup does not know that rule
  js = js.replace(/var\(--red\)/g, 'var(--red, #ef4444)').replace(/var\(--green\)/g, 'var(--green, #22c55e)');   // the desktop theme has no red/green variables
  written.push(write(`${name}.js`, js));
}

console.log(`wrote ${written.length} files into ${OUT}`);
for (const f of written) console.log('  ' + path.relative(OUT, f));
